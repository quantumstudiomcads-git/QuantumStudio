"""
Quantum Studio Calculation Definition

This module defines the universal description of a calculation.

The GUI, dependency compiler, workflow system, parameter system,
and execution backend all refer to calculations through this object.

A CalculationDefinition describes WHAT a calculation is.

It does not describe HOW the calculation is executed.
"""


from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class CalculationDefinition:

    # ---------------------------------------------------------
    # Identity
    # ---------------------------------------------------------

    id: str

    name: str

    category: str

    description: str = ""


    # ---------------------------------------------------------
    # Dependency system
    #
    # requires:
    # Artifacts that must exist before this calculation can run.
    #
    # produces:
    # Artifacts generated by this calculation.
    #
    # Example:
    #
    # SCF
    #   requires -> structure
    #   produces -> scf_result
    #
    # Bands
    #   requires -> scf_result
    #   produces -> band_structure
    # ---------------------------------------------------------

    requires: tuple[str, ...] = field(
        default_factory=tuple
    )

    produces: tuple[str, ...] = field(
        default_factory=tuple
    )


    # ---------------------------------------------------------
    # Workflow
    #
    # Identifies the workflow implementation responsible for
    # executing this calculation.
    # ---------------------------------------------------------

    workflow: str | None = None


    # ---------------------------------------------------------
    # Engine abstraction
    #
    # Examples:
    #
    # qe
    # phonopy
    # phono3py
    # boltztrap2
    # wannier90
    # negf
    #
    # This determines which backend engine adapter will eventually
    # execute the calculation.
    # ---------------------------------------------------------

    engine: str | None = None


    # ---------------------------------------------------------
    # Parameter schema
    #
    # This defines the parameters exposed to the GUI.
    #
    # Example:
    #
    # parameters={
    #
    #     "accuracy": {
    #         "type": "slider",
    #         "default": 3,
    #     },
    #
    #     "functional": {
    #         "type": "select",
    #         "options": ["PBE", "HSE"],
    #     },
    #
    # }
    # ---------------------------------------------------------

    parameters: dict[str, Any] = field(
        default_factory=dict
    )


    # ---------------------------------------------------------
    # Tags
    #
    # Used for:
    #
    # filtering
    # grouping
    # capability detection
    # automation
    # frontend organization
    # ---------------------------------------------------------

    tags: tuple[str, ...] = field(
        default_factory=tuple
    )


    # ---------------------------------------------------------
    # Metadata
    #
    # Reserved for future extensions.
    # ---------------------------------------------------------

    metadata: dict[str, Any] = field(
        default_factory=dict
    )
